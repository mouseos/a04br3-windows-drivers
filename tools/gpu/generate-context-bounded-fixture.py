"""Regenerate the default-off bounded context USC header from audited PCO output."""
import argparse
import hashlib
import importlib.util
import json
import pathlib

HERE=pathlib.Path(__file__).resolve().parent
EXPECTED=(('sr-store-bounded.bin','a04_context_store_bounded',712,'9b36731eb6064aa57c9bcce42b6f365e24087adade5bdb6cb2aad764f0e0345c',11),
          ('sr-load-bounded.bin','a04_context_load_bounded',560,'2034eb58fbc7dd3d6681d5ba1ee707a5d2b78b1759069c66c5b163ef118f7685',10))

def generate(source,build,diagnostic):
    diag=pathlib.Path(diagnostic);meta=json.loads((diag/'manifest.json').read_text())
    spec=importlib.util.spec_from_file_location('audit',HERE/'check-context-bounded-ir.py')
    audit=importlib.util.module_from_spec(spec);spec.loader.exec_module(audit)
    audit.check(source,build,diag)
    lines=['/* SPDX-License-Identifier: MIT',
           ' * Generated by tools/gpu/generate-context-bounded-fixture.py from pinned',
           ' * Mesa PCO. Diagnostic only; machine semantics and hardware are unverified. */',
           '#ifndef A04_RENDER_CONTEXT_BOUNDED_USC_H', '#define A04_RENDER_CONTEXT_BOUNDED_USC_H', '#include <stdint.h>']
    for filename,symbol,size,digest,temps in EXPECTED:
        data=(diag/filename).read_bytes();info=meta['files'][filename]
        if (len(data)!=size or hashlib.sha256(data).hexdigest()!=digest or info['sha256']!=digest or
            info['metadata_words'][0]!=temps):raise ValueError('unexpected bounded shader')
        lines.append('static const uint8_t %s[%d] = {'%(symbol,size))
        for i in range(0,size,12):lines.append('    '+','.join('0x%02x'%x for x in data[i:i+12])+',')
        lines.append('};')
    lines.extend(['#endif',''])
    return '\n'.join(lines)

def main():
    p=argparse.ArgumentParser(description=__doc__)
    for name in ('source','build','diagnostic','output'):p.add_argument('--'+name,type=pathlib.Path,required=True)
    p.add_argument('--check',action='store_true');a=p.parse_args()
    try:
        value=generate(a.source,a.build,a.diagnostic)
        if a.check:
            if a.output.read_text()!=value:raise ValueError('header mismatch')
        else:
            with a.output.open('x') as f:f.write(value)
    except (OSError,ValueError,KeyError,TypeError):raise SystemExit('bounded context fixture generation failed')
    print('bounded context header verified; GPU execution remains prohibited')
if __name__=='__main__':main()
