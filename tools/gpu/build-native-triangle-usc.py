"""既存host Mesaからsource NIRだけをcompile/linkし、生成USCの再現性とmetadataを固定する。GPU操作なし。"""
import argparse,hashlib,json,os,re,shlex,subprocess
from pathlib import Path
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def main():
    ap=argparse.ArgumentParser(description=__doc__)
    for x in ["build","compiler-archive","environment-libs","output","header"]:ap.add_argument("--"+x,type=Path,required=True)
    a=ap.parse_args();b=a.build.resolve();out=a.output.resolve();out.mkdir(parents=True,exist_ok=False)
    src=Path(__file__).resolve().parent/"shaders/native-triangle-usc.c"
    env=os.environ.copy();env.update(TMPDIR=str(out),LD_LIBRARY_PATH=str(a.environment_libs.resolve()),MESA_SHADER_CACHE_DISABLE="true")
    row=next(x for x in json.loads((b/"compile_commands.json").read_text()) if x["file"].endswith("/pco_nir.c"))
    mesa=(b/row["file"]).resolve().parents[3]
    # compile_commands source is src/imagination/pco/pco_nir.c.
    assert subprocess.check_output(["git","-C",str(mesa),"rev-parse","HEAD"],text=True).strip()=="0d94b3f397fb9cf8470bb5600ada8af79ff5361a"
    patch=subprocess.check_output(["git","-C",str(mesa),"diff","--binary"])
    (out/"mesa-working-source.patch").write_bytes(patch)
    sources={str(p.relative_to(mesa)):sha(p) for p in sorted((mesa/"src/imagination/pco").rglob("*")) if p.is_file() and p.suffix in (".c",".h",".py")}
    original=shlex.split(row["command"]);original=original[1:] if "ccache" in original[0] else original
    cmd=[];i=0
    while i<len(original):
        if original[i] in ["-o","-MF","-MT","-MQ"]:i+=2;continue
        if original[i] in ["-MD","-MMD"] or original[i]==row["file"]:i+=1;continue
        cmd.append(original[i]);i+=1
    cmd+=["-UNDEBUG","-Werror",str(src),"-o",str(out/"compiler.o")]
    subprocess.run(cmd,cwd=b,env=env,check=True)
    lines=subprocess.check_output(["ninja","-t","commands","src/imagination/vulkan/libvulkan_powervr_mesa.so"],cwd=b,env=env,text=True).splitlines()
    libs=[str(a.compiler_archive.resolve()) if x=="src/imagination/pco/libpowervr_compiler.a" else x
          for x in shlex.split(lines[-1]) if x.endswith((".a",".so")) and not x.startswith("-") and x!="src/imagination/vulkan/libvulkan_powervr_mesa.so"]
    link=["c++","-o",str(out/"compiler"),str(out/"compiler.o"),"-Wl,--start-group",*libs,"-Wl,--end-group","-pthread","-lm"]
    subprocess.run(link,cwd=b,env=env,check=True)
    runs=[subprocess.check_output([str(out/"compiler")],cwd=out,env=env) for unused in range(2)]
    assert runs[0]==runs[1],"source compiler output is nondeterministic"
    (out/"compiler-output.log").write_bytes(runs[0])
    text=runs[0].decode()
    assert "smp.2d.fcnorm" in text and "smp.3d" not in text
    assert "pck.scale.u8888" in text and "uvsw.write.emit.endtask" in text
    assert "load.global" not in text and "scratch" not in text
    # Hash actual thin-archive members too: a thin archive hash alone only
    # fixes the member path inventory, not the referenced object contents.
    link_inputs={}
    for name in libs:
        path=Path(name);path=path if path.is_absolute() else b/path
        link_inputs[str(path.resolve())]=sha(path)
        if path.suffix==".a" and path.read_bytes()[:8]==b"!<thin>\n":
            for member in subprocess.check_output(["ar","t",str(path)],text=True).splitlines():
                mp=Path(member);mp=mp if mp.is_absolute() else b/mp
                link_inputs[str(mp.resolve())]=sha(mp)
    regex=rb"PROGRAM (\d+) bytes=(\d+) temps=(\d+) shared=(\d+) vtxins=(\d+) vtxouts=(\d+)\n([0-9a-f]+)\n"
    parts=re.findall(regex,runs[0]);assert len(parts)==3
    meta=[];names=["vertex","solid","texture"]
    header="/* SPDX-License-Identifier: MIT\n * Generated by tools/gpu/build-native-triangle-usc.py from native-triangle-usc.c.\n * Mesa base0d94b3f397fb9cf8470bb5600ada8af79ff5361a, BVNC22.40.54.30.\n * Exact patched host compiler/source hashes are recorded in build manifest.\n * Source SHA256 "+sha(src)+". No GPU addresses are compiled in.\n */\n"
    for index,(n,size,temps,shared,ins,outs,hexdump) in enumerate(parts):
        vals=tuple(map(int,[n,size,temps,shared,ins,outs]))
        assert vals==[(0,40,0,0,2,4),(1,16,0,2,0,0),(2,64,5,8,0,0)][index],vals
        code=bytes.fromhex(hexdump.decode());assert len(code)==int(size)
        (out/(names[index]+".usc")).write_bytes(code)
        header+="static const uint8_t a04_triangle_"+names[index]+"_usc["+size.decode()+"]={\n"
        for at in range(0,len(code),8):header+="    "+",".join("0x%02x"%x for x in code[at:at+8])+",\n"
        header+="};\n"
        meta.append({"name":names[index],"bytes":len(code),"temps":int(temps),"shared":int(shared),"vtxins":int(ins),"vtxouts":int(outs),"sha256":hashlib.sha256(code).hexdigest()})
    a.header.write_text(header)
    manifest={"device_executed":False,"source":str(src),"source_sha256":sha(src),"build":str(b),
        "compiler_archive_sha256":sha(a.compiler_archive),"compile":cmd,"link":link,
        "mesa_pco_sources":sources,"mesa_working_patch_sha256":hashlib.sha256(patch).hexdigest(),"linked_object_hashes":link_inputs,
        "output_equal_across_two_processes":True,"programs":meta,"header_sha256":sha(a.header)}
    (out/"manifest.json").write_text(json.dumps(manifest,indent=2)+"\n")
if __name__=="__main__":main()
