int a04_gpu_linear_copy_fixture(void *pages,size_t size,struct rogue_fwif_cmd_transfer *command)
{
    uint8_t *p=pages; struct rogue_fwif_cmd_transfer unused; size_t i;
    if (!pages || !command || size!=(size_t)A04_GPU_LINEAR_COPY_PAGES*4096u) return -1;
    if (a04_gpu_copy_fixture(pages,(size_t)A04_GPU_COPY_PAGES*4096u,&unused)) return -1;
    /* The final PDS mapping moved after the two larger image buffers. */
    for(i=0;i<4096u;++i) p[293u*4096u+i]=p[289u*4096u+i];
    for(i=0;i<sizeof(differences)/sizeof(differences[0]);++i) p[differences[i].offset]=differences[i].value;
    return a04_gpu_decode_transfer(linear_stream,sizeof(linear_stream),0,command);
}
