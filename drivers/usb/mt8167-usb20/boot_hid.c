#define KEYBOARD_INPUT \
  0x05,0x01,0x09,0x06,0xa1,0x01,0x85,0x01, \
  0x05,0x07,0x19,0xe0,0x29,0xe7,0x15,0x00,0x25,0x01, \
  0x75,0x01,0x95,0x08,0x81,0x02,0x95,0x01,0x75,0x08,0x81,0x01, \
  0x95,0x06,0x75,0x08,0x15,0x00,0x25,0x65,0x05,0x07, \
  0x19,0x00,0x29,0x65,0x81,0x00
#define KEYBOARD_OUTPUT \
  0x05,0x08,0x19,0x01,0x29,0x05,0x15,0x00,0x25,0x01, \
  0x75,0x01,0x95,0x05,0x91,0x02,0x75,0x03,0x95,0x01,0x91,0x01
/* HID1.11 B.2's mandatory button/X/Y layout. Range includes every signed
 * 8-bit displacement. Five constant bytes give both Windows TLCs equal size;
 * no optional USB extension, wheel or extra button is advertised. */
#define MOUSE_INPUT \
  0x05,0x01,0x09,0x02,0xa1,0x01,0x85,0x02,0x09,0x01,0xa1,0x00, \
  0x05,0x09,0x19,0x01,0x29,0x03,0x15,0x00,0x25,0x01, \
  0x95,0x03,0x75,0x01,0x81,0x02,0x95,0x01,0x75,0x05,0x81,0x01, \
  0x05,0x01,0x09,0x30,0x09,0x31,0x15,0x80,0x25,0x7f, \
  0x75,0x08,0x95,0x02,0x81,0x06, \
  0x95,0x05,0x81,0x01,0xc0,0xc0
const unsigned char *A04BootHidDescriptor(unsigned output,unsigned *length)
{
 static const unsigned char input[]={KEYBOARD_INPUT,0xc0,MOUSE_INPUT};
 static const unsigned char leds[]={KEYBOARD_INPUT,KEYBOARD_OUTPUT,0xc0,MOUSE_INPUT};
 if(length)*length=output?(unsigned)sizeof(leds):(unsigned)sizeof(input);
 return output?leds:input;
}
int A04BootHidEncode(unsigned protocol,const unsigned char boot[8],unsigned char windows[9])
{
 unsigned i,n;unsigned char next[9]={0};
 if(!boot || !windows || (protocol!=A04_BOOT_KEYBOARD && protocol!=A04_BOOT_MOUSE))return -1;
 next[0]=(unsigned char)protocol;n=protocol==A04_BOOT_MOUSE?3u:8u;
 for(i=0;i<n;++i)next[i+1]=boot[i];
 if(protocol==A04_BOOT_MOUSE)next[1]&=7u;
 for(i=0;i<9;++i)windows[i]=next[i];
 return 0;
}
int A04BootHidMouseSnapshot(unsigned buttons,unsigned char windows[9])
{
 unsigned char boot[8]={0};boot[0]=(unsigned char)(buttons&7u);
 return A04BootHidEncode(A04_BOOT_MOUSE,boot,windows);
}
int A04BootHidKeyboardOutput(const KB_ENUM *k,const unsigned char *report,unsigned length,
 unsigned report_id,KB_CONTROL *control,unsigned char *led)
{
 if(!k || k->protocol!=A04_BOOT_KEYBOARD || !report || length!=2 ||
    report_id!=A04_BOOT_KEYBOARD || report[0]!=A04_BOOT_KEYBOARD)return -1;
 return KbOutputControl(k,report+1,1,0,control,led);
}
